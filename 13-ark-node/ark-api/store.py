def selftest():
    """The index quality filters, against synthetic artifacts and paths.

    NO DATABASE, NO INDEX, NO MODEL - the same shape as `bin/ark.py selftest`
    and for the same reason: a check that needs a 52 GB index and a loaded
    embedding model is a check nobody runs, and §8.10 says a second person must
    be able to rebuild this machine from printed instructions and find out
    whether it works. The fixtures are REAL PATHS taken from provenance.sqlite3
    on 2026-09-11, including the three that broke the rule as first written.

    What it cannot prove is written beside the green line: that the filters
    remove the number of chunks this module's comment claims. Only
    `serve.py --selftest` on the real index shows that, and it asserts it.
    """
    _MIRROR_SET_REAL = MIRROR_SET       # restored in the finally below
    s = Store.__new__(Store)
    s.artifacts = {
        1: {"file": "mdwiki_en_all_maxi_2025-11.zim"},
        2: {"file": "wikipedia_en_medicine_maxi_2026-04.zim"},
        4: {"file": "wikem_en_all_maxi_2026-07.zim"},
        8: {"file": "ifixit_en_all_2025-12.zim"},
        9: {"file": "ifixit_es_all_2026-03.zim"},
        26: {"file": "hesperian"},
    }
    s._mirror = frozenset({11, 12})
    s._mirror_state, s._mirror_detail = "ok", "synthetic"
    s._mirror_lock = threading.Lock()
    s._excl_stats = None

    ok = fail = 0

    def check(name, got, want, _unused="", note=""):
        nonlocal ok, fail
        if got == want:
            ok += 1
            print("  ok    %-8s %-24s %s" % (name, repr(got), note))
        else:
            fail += 1
            print("  FAIL  %-8s got %r, want %r  %s" % (name, got, want, note))

    def ex(src, dnum, path):
        return s.excluded({"src": src, "dnum": dnum, "path": path})

    # --- iFixit -------------------------------------------------------------
    # THE SHAPE THE ONE-LINE RULE IN DECISIONS.md WOULD HAVE MISSED. 297,175 of
    # the 297,242 user pages start with the segment; only 67 carry a full URL.
    check("ifixit", ex(8, 1, "User/1098034/Don Joseph"), "user_profile",
          "", "leading segment, the 297,175 case")
    check("ifixit", ex(9, 1, "ttps://es.ifixit.com/User/1136102/Greg Hamilton"),
          "user_profile", "", "embedded URL, the 67 case")
    # and the content the artifact is here for is untouched
    check("ifixit", ex(8, 2, "Guide/Install+a+battery/12345"), None, "", "a guide is kept")
    check("ifixit", ex(8, 3, "Device/15%s_MacBook_Pro_(Early_2006)" % "″"),
          None, "", "a device is kept")
    check("ifixit", ex(9, 4, "Desmontaje/2016+Moto+Z+Teardown/144150"), None,
          "", "a teardown is kept")
    # A PAGE ABOUT USERS IS NOT A USER PAGE.
    check("ifixit", ex(8, 5, "Guide/How+to+add+a+User+account/99"), None,
          "", "'User' mid-title is not the User/ tree")

    # --- wikem --------------------------------------------------------------
    check("wikem", ex(4, 1, "100kg_(large_Adult)/vi"), "translation")
    check("wikem", ex(4, 2, "Advil/ru"), "translation")
    check("wikem", ex(4, 3, "Advil/zh"), "translation")
    check("wikem", ex(4, 4, "Advil/es"), None, "", "Spanish is kept, Juan 09-11")
    check("wikem", ex(4, 5, "Advil"), None, "", "the English original is kept")
    # THE NAMED-LIST RULE, STATED AS A TEST. A two-letter final segment that is
    # not a language we dropped is SHOWN. Failing toward showing is the safe
    # direction, and this is the assertion that says so out loud.
    check("wikem", ex(4, 6, "Vitamin/b6"), None, "", "unknown 2-char tail is shown")
    check("wikem", ex(4, 7, "Something/is"), None, "", "'is' is not in the list")
    check("wikem", len(s.WIKEM_DROP), 14, "", "fourteen languages dropped")
    check("wikem", "es" in s.WIKEM_DROP, False, "", "es is never in the drop list")
    check("wikem", "en" in s.WIKEM_DROP, False, "", "en carries no suffix at all")

    # --- mdwiki -------------------------------------------------------------
    check("mdwiki", ex(1, 11, "Oral_rehydration_therapy"), "mirror")
    check("mdwiki", ex(1, 99, "Enoxaparin"), None, "", "mdwiki-only article is kept")
    # SHARING A PATH IS NO LONGER ENOUGH, WHICH IS THE 09-12 NARROWING.
    # dnum 77 stands for an article wikipedia_en_medicine also has at the same
    # path, whose mdwiki version carries an infobox the newer one lost -
    # Tafamidis, Fixed_drug_reaction - so it is NOT in the generated set and is
    # shown. Under the one-day-old "same path" rule it would have been dropped.
    check("mdwiki", ex(1, 77, "Tafamidis"), None,
          "", "shared path but not in the set: both copies are shown")
    # AND THE RULE IS ONE-DIRECTIONAL. wikipedia_en_medicine is the artifact
    # being kept; excluding both sides of a mirror would remove the article.
    check("mdwiki", ex(2, 11, "Oral_rehydration_therapy"), None,
          "", "the newer side is never excluded")

    # --- the generated set, when it is not there or not trustworthy ----------
    # EVERY FAILURE PATH MUST SHOW BOTH COPIES, NOT HIDE ONE. A stale set points
    # at documents nobody compared, so the rule is switched off rather than
    # applied - and `mirror_state` says which of the two zeroes this is.
    import tempfile
    _keep = (s._mirror, s._mirror_state)
    try:
        s._mirror = None
        s._mirror_state = s._mirror_detail = None
        globals()["MIRROR_SET"] = os.path.join(
            tempfile.gettempdir(), "ark-mirror-does-not-exist.json")
        check("set", ex(1, 11, "Oral_rehydration_therapy"), None,
              "", "no set file: the mirror rule does not fire")
        check("set", s._mirror_state, "absent", "", "and it says why")

        s._mirror = None
        s._mirror_state = s._mirror_detail = None
        bad = os.path.join(tempfile.gettempdir(), "ark-mirror-bad.json")
        with open(bad, "w", encoding="utf-8") as fh:
            fh.write("{not json")
        globals()["MIRROR_SET"] = bad
        check("set", ex(1, 11, "Oral_rehydration_therapy"), None,
              "", "unreadable set: the rule does not fire")
        check("set", s._mirror_state, "unreadable", "", "and it says why")

        s._mirror = None
        s._mirror_state = s._mirror_detail = None
        stale = os.path.join(tempfile.gettempdir(), "ark-mirror-stale.json")
        with open(stale, "w", encoding="utf-8") as fh:
            json.dump({"dnums": [11, 12], "old": {"jsonl": "nope-old.jsonl"},
                       "new": {"jsonl": "nope-new.jsonl"},
                       "stamp": {"old_jsonl": {"size": 1, "mtime": 1},
                                 "new_jsonl": {"size": 1, "mtime": 1},
                                 "provenance": {"size": 1, "mtime": 1}}}, fh)
        globals()["MIRROR_SET"] = stale
        check("set", ex(1, 11, "Oral_rehydration_therapy"), None,
              "", "stale set: the rule does not fire")
        check("set", s._mirror_state, "stale", "", "and it says why")
    finally:
        globals()["MIRROR_SET"] = _MIRROR_SET_REAL
        s._mirror, s._mirror_state = _keep

    # --- an archive without the pair (the starter kit) ------------------------
    _arts = s.artifacts
    try:
        s.artifacts = {8: {"file": "ifixit_en_all_2025-12.zim"}}
        s._mirror = None
        s._mirror_state = s._mirror_detail = None
        globals()["MIRROR_SET"] = os.path.join(
            tempfile.gettempdir(), "ark-mirror-does-not-exist.json")
        check("set", (s._mirrored_dnums(), s._mirror_state, s._mirror_detail),
              (frozenset(), "not_needed", None), "",
              "no mdwiki in the archive: nothing to compare, not degraded")
    finally:
        globals()["MIRROR_SET"] = _MIRROR_SET_REAL
        s.artifacts = _arts
        s._mirror, s._mirror_state = _keep

    # --- everything else ----------------------------------------------------
    check("other", ex(26, 1, "en_cgeh_2012_full.pdf"), None, "", "PDF shelves untouched")
    check("other", s.excluded({"src": 404, "dnum": 1, "path": "x"}), None,
          "", "an unknown artifact is shown, not hidden")

    # --- the switch ---------------------------------------------------------
    # ARK_NO_FILTERS=1 HAS TO TURN OFF ALL THREE, not two of them. A measurement
    # comparing with and against a partially-disabled filter would be worse than
    # no measurement, because it would look like one.
    try:
        Store.EXCLUDE_OFF = True
        check("switch", ex(8, 1, "User/1/x"), None, "", "iFixit off")
        check("switch", ex(4, 1, "Advil/vi"), None, "", "wikem off")
        check("switch", ex(1, 11, "Oral_rehydration_therapy"), None, "", "mdwiki off")
    finally:
        Store.EXCLUDE_OFF = os.environ.get("ARK_NO_FILTERS") == "1"

    # --- PQ coverage --------------------------------------------------------
    # THE FIXTURE IS THE REAL 2026-09-24 SHAPE: an index built on 09-15 over the
    # 48 artifacts of passes 1 and 2, and a registry that has since grown two
    # Wikipedias worth 32,147,292 chunks. `pq.state` reads `ok` in that
    # situation, `dense_error` is null and nothing else on the health page says
    # a word, which is the window this check exists to close.
    _man = {"stamp": {"artifacts": [["mdwiki_en_all_maxi_2025-11.zim", 300100, 614604928],
                                    ["wikem_en_all_maxi_2026-07.zim", 302855, 620247168]]}}
    _reg = {"artifacts": {
        "1": {"file": "mdwiki_en_all_maxi_2025-11.zim", "chunks": 300100},
        "4": {"file": "wikem_en_all_maxi_2026-07.zim", "chunks": 302855},
        "49": {"file": "wikipedia_es_all_maxi_2026-05.zim", "chunks": 7004952},
        "50": {"file": "wikipedia_en_all_maxi_2026-02.zim", "chunks": 25142340}}}

    check("pqcov", pq_coverage(_man, _reg),
          (602955, 32750247, ["wikipedia_en_all_maxi_2026-02.zim",
                              "wikipedia_es_all_maxi_2026-05.zim"]),
          "", "an index one pass behind is NAMED, not counted")

    # AN EMPTY `missing` IS THE HEALTHY ANSWER AND IT IS NOT THE SAME VALUE AS
    # None. serve.py branches on the list, so a check that returned None for
    # "no gap" and None for "no manifest" would report the same thing twice.
    _full = {"stamp": {"artifacts": [[a["file"], a["chunks"], 0]
                                     for a in _reg["artifacts"].values()]}}
    check("pqcov", pq_coverage(_full, _reg), (32750247, 32750247, []),
          "", "a current index: covered == total, nothing named")

    # DRIFT IS THE OTHER DIRECTION AND IS NOT THIS CHECK'S JOB. _pq_plan()
    # already catches a vector file that moved, by size, and refuses to load.
    # Counting it here too would put one fault in two voices.
    _extra = {"stamp": {"artifacts": [["gone_from_the_registry.zim", 5, 0],
                                      ["mdwiki_en_all_maxi_2025-11.zim", 300100, 0]]}}
    check("pqcov", pq_coverage(_extra, _reg)[0], 300100,
          "", "an artifact only the MANIFEST has is ignored")

    # A REGISTRY ROW WITH NO COUNT MUST NOT SILENTLY BECOME A COVERED ONE.
    check("pqcov", pq_coverage(_man, {"artifacts": {
              "9": {"file": "half_written.zim"}}}),
          (0, 0, ["half_written.zim"]), "", "no `chunks` key counts as zero, still named")

    check("pqcov", pq_coverage({}, _reg)[2] == sorted(
              a["file"] for a in _reg["artifacts"].values()), True,
          "", "no stamp at all: every artifact is missing, and none is dropped")

    print("\n%d/%d" % (ok, ok + fail))
    return fail == 0


