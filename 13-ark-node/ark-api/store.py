_NUMPY_VERSION = None


def preimport():
    """Import numpy once, under a lock this module shares across both loaders.

    RAISES on failure, so both call sites record the real exception through the
    handler they already have rather than through a string. Idempotent and cheap
    after the first call: one lock acquisition and a bool.

    `numpy.linalg` is named explicitly because it is where the observed failure
    re-entered - importing the parent alone would leave the same submodule to be
    pulled in later by faiss or torch, on whatever thread got there first."""
    global _NUMPY_READY, _NUMPY_VERSION
    if _NUMPY_READY:
        return
    with _IMPORT_LOCK:
        if _NUMPY_READY:
            return
        import numpy                                          # noqa: F401
        import numpy.linalg                                   # noqa: F401
        _NUMPY_VERSION = getattr(numpy, "__version__", None)
        _NUMPY_READY = True


def numpy_version():
    """The numpy this process imported, or None if it never got that far.

    Deliberately NOT `import numpy; numpy.__version__` on demand: that would
    answer "what would import now", and this has to answer "what DID import, on
    the main thread, at startup" - which on 2026-09-16 were different answers.
    numpy 2.5.2 imported cleanly from a shell all evening while the running
    server could not import it at all."""
    return _NUMPY_VERSION

