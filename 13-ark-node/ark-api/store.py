def _quasi(path):
    """Percent-encode a path, leaving the separators alone.

    NOT COSMETIC. Two real entries in this archive break an unencoded URL:

        appropedia   Are_You_Ready?/Floods
        fao          Irrigation/Respuesta del rendimiento de los cultivos al agua.pdf

    The first carries a literal `?`, which starts a query string the moment it
    lands in a path - so /content/<book>/Are_You_Ready?/Floods asks kiwix-serve
    for `Are_You_Ready` with a query, and gets a 404. The second carries spaces.
    Both were found by reading the first four results of the first three test
    questions, which is the argument for testing against the real corpus rather
    than a fixture.

    `safe="/"` is what kiwix-serve's own viewer does - its source calls the
    result `quasiUriEncodedPath`, encoding everything except the separator, and
    matching it is how a link built here opens in the viewer built there."""
    return urllib.parse.quote(path, safe="/")


def _load_bin(name):
    """Import a tool from bin/ by path. Their filenames carry hyphens, so they are
    not importable by name, and renaming them would break every runbook that
    names them.

    KNOWN COUPLING, RECORDED RATHER THAN HIDDEN: the stoplist lives in
    bin/index-bm25.py and this reuses it instead of copying it. A second copy
    would drift, and the stoplist is the file where drift is least acceptable -
    it is hand-tuned for THIS corpus, where `well` is a water well. When
    13-ark-node becomes its own repository, bin/ moves into it as ops/ per
    NODE-ARCHITECTURE §6 and this import becomes local."""
    path = os.path.join(BIN, name)
    if not os.path.exists(path):
        raise RuntimeError("%s is missing; the node cannot search without it" % path)
    spec = importlib.util.spec_from_file_location(name.replace("-", "_")[:-3], path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod



class _Rows(list):
    """What `Shared.execute` hands back: rows already fetched.

    Returning a live cursor would defeat the lock, because the statement stays
    open until the caller finishes iterating and another thread can reach it in
    the meantime. Everything the node asks of this index is small enough to
    materialise."""

    def fetchone(self):
        return self[0] if self else None

    def fetchall(self):
        return list(self)


def expand_followup(q, prev_qs):
    """The retrieval string for a follow-up, or None if there is nothing to add.

    A thin delegate to `bin/index-bm25.py`, which owns the tokenizer and the
    stoplist. The coupling is the one `_load_bin` documents at length: a second
    copy of a stoplist hand-tuned for THIS corpus, where `well` is a water well,
    is the drift least worth risking. Guarded because §3.4 does not let a
    retrieval path require something that can be absent - no `bin/`, no
    expansion, and the follow-up is retrieved as the standalone question it
    looks like."""
    try:
        return _load_bin("index-bm25.py").expand_followup(q, prev_qs)
    except Exception:                                # noqa: BLE001 - optional
        return None


class Shared(object):
    """A read-only SQLite connection that several request threads may use.

    `check_same_thread=False` switches off Python's own check and puts nothing
    in its place. The connection still has ONE prepared-statement cache, so two
    threads running the SAME SQL TEXT are handed the SAME `sqlite3_stmt`: one
    binds while the other is mid-step, SQLite returns SQLITE_MISUSE, and
    pysqlite raises `InterfaceError: bad parameter or other API misuse`.

    IT LANDS ON WHICHEVER STATEMENT RUNS MOST OFTEN, which is why it looked like
    two unrelated defects. Found 2026-09-07 in a browser, with tracebacks:

        store.py   meta()       SELECT ... FROM chunk c JOIN doc d ...
        spatial.py _is_place()  SELECT 1 FROM place WHERE norm = ? LIMIT 1

    The first has been reachable since the surface began firing /api/search and
    /api/answer in parallel on 2026-09-04, and survived on timing. The second
    arrived with passage places, which ask that question a few hundred times per
    passage across twenty passages - and that is what took a rare collision to a
    certain one. **A latent concurrency defect is not a rare defect. It is a
    defect waiting for the load that makes it certain.**

    THE LOCK IS HELD ACROSS EXECUTE AND FETCH. Releasing between them leaves the
    statement live and is the same misuse in slower motion. These queries are
    microseconds; the BM25 MATCH is the only slow one, and two concurrent
    searches already contended on it inside SQLite.

    NOT thread-local connections, which was the other candidate: this server
    makes a thread per request, so that means opening and discarding a
    connection per request, and it hides the contention rather than bounding it.
    """

    def __init__(self, db):
        self._db = db
        self._lock = threading.Lock()

    @property
    def row_factory(self):
        return self._db.row_factory

    @row_factory.setter
    def row_factory(self, f):
        self._db.row_factory = f

    def execute(self, sql, params=()):
        with self._lock:
            return _Rows(self._db.execute(sql, params).fetchall())

    def close(self):
        with self._lock:
            self._db.close()


class Store:
    def __init__(self):
        # WRAPPED, NOT BARE. Both are read by every request thread at once; see
        # Shared above for what a bare shared connection does under load.
        self.prov = Shared(sqlite3.connect(
            "file:%s?mode=ro" % PROV_DB.replace("\\", "/"),
            uri=True, check_same_thread=False))
        self.prov.row_factory = sqlite3.Row
        self.bm = Shared(sqlite3.connect(
            "file:%s?mode=ro" % BM25_DB.replace("\\", "/"),
            uri=True, check_same_thread=False))
        self.artifacts = {r["src"]: dict(r) for r in
                          self.prov.execute("SELECT * FROM artifact")}

        # THE BOOK KEY IN A URL IS THE ZIM'S FILENAME STEM, which is what
        # sources.json already records as `kiwix_book`. That is worth a comment
        # only because it was "corrected" to something else on 2026-09-04 and the
        # correction was wrong.
        #
        # kiwix-manage reports a book `name` taken from ZIM metadata -
        # `appropedia_en_all` - and all 25 artifacts here disagree with their
        # filename stem, which made the stems look obviously broken. A live
        # kiwix-serve settled it:
        #
        #     /content/appropedia_en_all              404
        #     /content/appropedia_en_all_maxi_2026-02 200
        #
        # kiwix-serve builds the URL from the FILE PATH. Its own catalogue prints
        # both fields side by side - href="/content/mdwiki_en_all_maxi_2025-11"
        # against <name>mdwiki_en_all</name> - and only the first is a URL.
        #
        # So `kiwix-books.json` records the key a RUNNING server was observed
        # answering to, matched to an artifact by the last path segment. Its
        # absence is not an error; it means nothing has been confirmed, the
        # filename stem is used as a fallback, and the citation is labelled
        # book_verified=false rather than implying a check that never happened.
        self.books = {}
        self.books_from = None
        # THE PATH, NOT THE URL, AND THEY ARE DIFFERENT FIELDS.
        # `books_from` is `verified_against` when present - the SERVER the keys
        # were confirmed against, e.g. http://localhost:8080 - and only falls
        # back to the library path. `unindexed()` needs the FILE, and reading
        # `books_from` for it silently found nothing: os.path.exists() on a URL
        # is False, so 67 books read as zero and the fallback never appeared.
        # Caught by serve.py --selftest, which reports the absence rather than
        # printing a green line about a link it never built.
        self.books_library = None
        self.books_stale = None
        if os.path.exists(BOOKS):
            d = json.load(open(BOOKS, encoding="utf-8"))
            self.books = {int(k): v.get("key") for k, v in d["books"].items()}
            self.books_from = d.get("verified_against") or d.get("from_library")
            self.books_library = d.get("from_library")
            # IS THIS FILE STILL ABOUT THE LIBRARY THAT IS RUNNING?
            # Rebuilding library.xml changes the keys kiwix-serve answers to, and
            # a kiwix-books.json left over from the previous one produces
            # citations that look verified and 404. That happened twice on
            # 2026-09-04, and both times the only symptom was a dead link.
            lib = d.get("from_library")
            if lib and os.path.exists(lib) and d.get("library_mtime"):
                st = os.stat(lib)
                if (int(st.st_mtime) != d["library_mtime"]
                        or st.st_size != d.get("library_size")):
                    self.books_stale = (
                        "%s was rebuilt after these book keys were recorded. Every "
                        "ZIM citation may 404. Re-run: python bin/kiwix-library.py "
                        "--verify-against <kiwix url>" % lib)
        self._terms = None
        self._dense = None
        self._dense_error = None
        self._dense_lock = threading.Lock()
        # The PQ half, loaded under its own lock for the reason the Chroma half
        # has one: ThreadingMixIn means two handler threads can arrive together.
        self._pq = None
        self._pq_error = None
        self._pq_state = None           # absent | stale | ok | error
        self._pq_detail = None
        self._pq_lock = threading.Lock()
        # The mdwiki mirror set is loaded once, lazily, under a lock for the
        # same reason the dense half is: ThreadingMixIn means two handler
        # threads can arrive together, and reading and parsing the same file
        # twice is waste at the exact moment the node is busiest.
        self._mirror = None
        self._mirror_state = None       # ok | absent | stale | unreadable
        self._mirror_detail = None      # one sentence, shown rather than logged
        self._mirror_lock = threading.Lock()
        self._excl_stats = None
        self._unindexed = None

    # ---------------------------------------------------------------- search

    def terms(self, q):
        if self._terms is None:
            self._terms = _load_bin("index-bm25.py").query_terms
        return self._terms(q)

    def _match(self, expr, n):
        try:
            rows = self.bm.execute(
                "SELECT cid FROM chunks WHERE chunks MATCH ? ORDER BY bm25(chunks) LIMIT ?",
                (expr, n)).fetchall()
        except sqlite3.OperationalError as e:
            raise RuntimeError("BM25 query failed: %s" % e)
        return [r[0] for r in rows]

    def place_words(self, q):
        """Which of the query's content words name a place, per the gazetteer.

        LAZY AND OPTIONAL, both deliberately. `spatial` imports this module, so
        importing it at the top would be circular; and §3.4 says nothing gating
        retrieval may require a component that can be absent. No gazetteer, or
        any failure at all, returns the empty set and the caller falls straight
        back to the plain OR query. The gazetteer needs no model - it is one
        SQLite file - so this costs nothing the keyword floor cannot pay.

        IT DELIBERATELY DOES NOT USE `is_place_reference`, WHICH ANSWERS A
        DIFFERENT QUESTION. That test asks *is this question asking about the
        place*, and to keep the spatial card honest it requires a locative
        preposition in front of the name. On `groundwater in Nevada and Utah` it
        accepts Nevada (`prev="in"`) and rejects Utah (`prev="and"`) - correct
        for a card that must not fire on 83,856 real non-spatial questions, and
        wrong here, where the only question is whether a token NAMES a place so
        it can be treated as a qualifier rather than as the subject.

        Using it left `utah` in the topic group, so the scoped query became
        `("groundwater" OR "utah") AND ("nevada")`, which matches the same
        nevada+utah chunks and changed nothing. Measured, not reasoned.

        SO THIS TAKES THE PASSAGE GUARDS WITHOUT THAT BASE: not a free capital,
        `poprank >= PASSAGE_POPRANK` (below it the residue is led by `Valley` and
        `University`, the generic tails of longer proper nouns), and not in
        `AMBIGUOUS`, which is where `turkey`, `nice`, `mobile` and `reading`
        live. A false positive here is cheap - a word becomes a qualifier
        instead of a subject - and if every content word is classified as a
        place the topic group empties and the caller falls back."""
        try:
            import spatial
            if not spatial.available():
                return set()
            out = set()
            for m in spatial.mentions(q):
                if m["clause"]:
                    continue
                if m["poprank"] < spatial.PASSAGE_POPRANK:
                    continue
                if m["text"].lower() in spatial.AMBIGUOUS:
                    continue
                out.update(w for w in m["text"].lower().split() if len(w) > 1)
            return out
        except Exception:                            # noqa: BLE001 - optional
            return set()

    def keyword(self, q, n):
        """The sparse half. Returns chunk ids, best first.

        THIS IS THE SHIPPED PATH AND IT IS THE PLAIN `OR` QUERY. The scoped
        candidate below is NOT on it - see `keyword_scoped`."""
        m = self.terms(q)
        if not m:
            return []
        return self._match(m, n)

    def keyword_scoped(self, q, n):
        """CANDIDATE, NOT SHIPPED. `keyword()` is what the surface calls.

        Topic AND place first, then the plain `OR` query fills the rest, so it
        can only reorder results and never lose them. It exists to fix a real,
        measured defect: `groundwater in Nevada and Utah` returned twelve top
        results containing `groundwater` ZERO times, because in a medical corpus
        `nevada` (1,665 chunks) and `utah` (2,313) are rarer than `groundwater`
        (3,510) and BM25 ranks by rarity. See `query_scoped` in
        bin/index-bm25.py for why counting matched terms does not fix it.

        WHY IT IS NOT SHIPPED: MEASURED AND REJECTED, 2026-09-08.
        Reproduce with `python bin/measure-retrieval.py --scoped`.

        1,079 of the archive's own 83,856 Stack Exchange question titles name a
        place and still have a subject left over. Over 120 of them, sampled with
        a fixed seed:

            slots  topic  place   both
            1200   98.2%  72.7%  70.9%   shipped
            1200  100.0%  98.7%  98.7%   scoped

        and the rule rewrote the page on **91 of 120 queries, 76%**.

        THE DEFECT IT WAS BUILT FOR DOES NOT HAPPEN. `groundwater in Nevada and
        Utah` returns twelve results with `groundwater` nowhere in them, and
        that is genuine - but on those 120 real questions the shipped page
        contained **zero topic terms 0 times and zero place terms 0 times**. The
        98.2% is per-slot noise, not a page that lost its subject. The
        motivating query was one I wrote, not one anyone asked, and it is rarer
        than 1 in 120 in the archive's own questions.

        So the rule rewrites three quarters of place-bearing pages to fix
        something that essentially never occurs, and a rescue-only variant -
        scope only when the plain page has no topic term - would never fire at
        all. The `earthquake building codes in Japan` regression, which promoted
        a US flood timeline over an earthen-building text, is therefore not an
        edge case but the same mechanism working on 76% of queries.

        KEPT RATHER THAN DELETED so the rejection is a command anyone can re-run
        offline instead of a claim in a log, and because the BM25 finding
        underneath it stands: in this corpus `nevada` and `utah` are rarer than
        `groundwater`, so rarity and relevance point in different directions and
        any future ranking work has to start there.

        It lives here rather than in the measurement script so there is ONE copy
        of the rule. A measurement holding its own copy agrees with itself
        forever, which this build has now been bitten by three times."""
        bm25 = _load_bin("index-bm25.py")
        m = bm25.query_terms(q)
        if not m:
            return []

        ids, seen = [], set()
        places = self.place_words(q)
        if places:
            words = bm25.content_words(q)
            topic = [w for w in words if w not in places]
            place = [w for w in words if w in places]
            scoped = bm25.query_scoped(topic, place)
            if scoped:
                for cid in self._match(scoped, n):
                    if cid not in seen:
                        seen.add(cid); ids.append(cid)

        for cid in self._match(m, n):
            if len(ids) >= n:
                break
            if cid not in seen:
                seen.add(cid); ids.append(cid)
        return ids[:n]

    # ------------------------------------------------------------ the PQ half

    def _pq_plan(self):
        """(state, detail, plan) for the PQ index, without importing anything.

        FOUR STATES AND THEY ARE NOT THE SAME FACT, which is the rule this file
        already follows for `unindexed()` and the mirror set. ABSENT is normal -
        the index is new and this node ran without it for two weeks. STALE means
        the vectors on disk are not the ones it was built from, which would
        return citations for the wrong passages, so it is never used.

        The row offsets are derived from the manifest's own stamp rather than
        recomputed from sources.json: the stamp is [slug, rows, bytes] per
        artifact IN BUILD ORDER, which is exactly the cumulative sum needed, and
        deriving them from the same record that is being checked for staleness
        means the two can never disagree."""
        man_p = os.path.join(PQ_DIR, "manifest.json")
        if not os.path.exists(man_p):
            return "absent", "no PQ index; build it with bin/index-pq-build.py", None
        try:
            man = json.load(open(man_p, encoding="utf-8"))
        except Exception as e:                                 # noqa: BLE001
            return "error", "%s is unreadable (%s)" % (man_p, type(e).__name__), None
        ipath = os.path.join(PQ_DIR, man.get("index", ""))
        rpath = os.path.join(PQ_DIR, man.get("rows", "rows.npy"))
        for f in (ipath, rpath):
            if not os.path.exists(f):
                return "absent", "%s names %s and it is not there" % (
                    os.path.basename(man_p), os.path.basename(f)), None

        plan, base, drift = [], 0, []
        for slug, n, size in (man.get("stamp") or {}).get("artifacts", []):
            vf = os.path.join(INDEX, "vectors", slug + ".f16.npy")
            if not os.path.exists(vf):
                drift.append("%s is gone" % slug)
            elif os.path.getsize(vf) != size:
                drift.append("%s is %d bytes, was %d" % (slug, os.path.getsize(vf), size))
            plan.append((slug, int(n), base, vf))
            base += int(n)
        if not plan:
            return "error", "%s carries no artifact stamp" % os.path.basename(man_p), None
        if drift:
            return ("stale",
                    "the vectors changed since this index was built (%s%s). "
                    "Rebuild: python bin/index-pq-build.py"
                    % ("; ".join(drift[:3]), ", and %d more" % (len(drift) - 3)
                       if len(drift) > 3 else ""), None)
        return "ok", None, (man, ipath, rpath, plan, base)

    def _load_pq(self):
        """faiss index + row map + the vector files the rerank scores against.

        NOTHING HERE IS IMPORTED UNTIL A QUERY ASKS FOR IT, same as the Chroma
        half, so a node with no faiss and no numpy still serves keyword search
        and says why rather than failing to start."""
        with self._pq_lock:
            if self._pq is not None or self._pq_error is not None:
                return
            state, detail, plan = self._pq_plan()
            self._pq_state, self._pq_detail = state, detail
            if state != "ok":
                if state in ("stale", "error"):
                    self._pq_error = detail
                return
            man, ipath, rpath, arts, total = plan
            try:
                preimport()          # numpy whole, once - see the note above
                import faiss
                import numpy as np
                from sentence_transformers import SentenceTransformer
                os.environ["HF_HUB_OFFLINE"] = "1"
                os.environ["TRANSFORMERS_OFFLINE"] = "1"
                ix = faiss.read_index(ipath)
                if ix.ntotal != total:
                    self._pq_state = "stale"
                    self._pq_error = self._pq_detail = (
                        "the index holds %s vectors and the row map describes %s - "
                        "refusing to use it, because every citation past the first "
                        "disagreement would name the wrong passage"
                        % ("{:,}".format(ix.ntotal), "{:,}".format(total)))
                    return
                rows = np.load(rpath, mmap_mode="r")
                if rows.shape[0] != total:
                    self._pq_state = "stale"
                    self._pq_error = self._pq_detail = (
                        "rows.npy is %s rows, the index is %s"
                        % ("{:,}".format(rows.shape[0]), "{:,}".format(total)))
                    return
                model = SentenceTransformer(
                    os.path.join(ROOT, "01-models", "tier4-embedding", "bge-m3"),
                    local_files_only=True)
                model.half()
                self._pq = (ix, rows, arts, model, man, total)
                self._pq_state, self._pq_detail = "ok", None
            except Exception as e:                             # noqa: BLE001
                tb = traceback.extract_tb(e.__traceback__)
                where = " <- ".join(
                    "%s:%d %s" % (os.path.basename(f.filename), f.lineno, f.name)
                    for f in tb[-4:])
                self._pq_state = "error"
                self._pq_error = self._pq_detail = "%s: %s [%s]" % (
                    type(e).__name__, e, where)

    def _pq_search(self, q, n, depth):
        """Nominate with PQ, score with the real float16 vectors.

        THE RERANK IS THE WHOLE POINT AND IT IS CHEAP. PQ64 alone is r@5 0.425;
        the same index handing `depth` candidates to an exact inner product over
        vectors/*.npy reaches 0.975, for about 6.6 ms, because `depth` rows of
        2 KB from a memory-mapped array is 400 KB of reads. Anything that skips
        this step is using a much worse index and will not be told so."""
        import numpy as np
        ix, rows, arts, model, _man, total = self._pq
        v = np.asarray(model.encode([q], normalize_embeddings=True), dtype=np.float32)
        _d, cand = ix.search(v, min(depth, total))
        cand = [int(c) for c in cand[0] if c >= 0]
        if not cand:
            return [], {}

        # The real vectors for those rows, looked up by bisect on the artifact
        # bases. A row that cannot be placed RAISES rather than scoring as a
        # zero vector, which would read as orthogonal, sort last, and look like
        # recall lost to quantization. Same reason index-pq-probe.gather() does.
        import bisect
        bases = [a[2] for a in arts]
        M = np.empty((len(cand), v.shape[1]), dtype=np.float32)
        cache = {}
        for pos, g in enumerate(cand):
            ai = bisect.bisect_right(bases, g) - 1
            if ai < 0 or not (arts[ai][2] <= g < arts[ai][2] + arts[ai][1]):
                raise RuntimeError("PQ row %d is outside every artifact" % g)
            mm = cache.get(ai)
            if mm is None:
                mm = cache[ai] = np.load(arts[ai][3], mmap_mode="r")
            M[pos] = np.asarray(mm[g - arts[ai][2]], dtype=np.float32)
        nrm = np.linalg.norm(M, axis=1, keepdims=True)
        nrm[nrm == 0] = 1.0
        score = (M / nrm) @ v[0]

        order = np.argsort(-score)[:n]
        ids, out = [], {}
        for k in order:
            r = rows[cand[int(k)]]
            cid = "%d:%d:%d" % (int(r[0]), int(r[1]), int(r[2]))
            ids.append(cid)
            out[cid] = float(score[int(k)])
        return ids, out

