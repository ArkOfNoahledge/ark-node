# `self._pq_lock`; `_load_dense` imports chromadb and sentence_transformers
# under `self._dense_lock`. Both pull numpy and THE TWO LOCKS DO NOT EXCLUDE
# EACH OTHER, on a process that also runs cross-check jobs, spatial and safety
# on their own threads.
#
# WHICH THREAD WAS SECOND IS NOT KNOWN AND THE FIX DOES NOT DEPEND ON IT. If
# numpy is fully imported before any request thread exists, no thread can ever
# see it half-built. `serve.py` calls preimport() on the main thread at startup;
# the lock below covers whatever reaches this module first when it has not.
#
# IT DOES NOT TOUCH THE LAZY LOAD. numpy is about 0.1 s and ~30 MB and pulls in
# neither faiss, nor the 443 MB index, nor bge-m3, so the 2026-09-15 decision -
# a node that never asks a dense question never pays for one - is unchanged.
