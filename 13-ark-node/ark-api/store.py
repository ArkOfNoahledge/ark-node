    #
    #    THE DROPPED LANGUAGES ARE NAMED RATHER THAN MATCHED BY SHAPE. A regex
    #    for *any* two-letter final segment would also eat a real article whose
    #    title ends that way, and the copy-pairs matcher in `bin/copy-pairs.sh`
    #    already states the principle this build follows: a pattern that does
    #    not understand something fails to match, so the item is SHOWN rather
    #    than hidden. That is the safe direction to be wrong in. The cost is
    #    that a language appearing in a future wikem snapshot is kept until
    #    this list is updated, which is visible rather than silent.
    #
    # 3. mdwiki mirror. 97.7% of mdwiki's articles are also in
    #    `wikipedia_en_medicine_maxi`, and 97.0% of its chunks. Sampling 200 of
    #    those articles and comparing the full document text: **52% are
    #    byte-identical, 30% are >=0.90 similar, 18% are a different revision.**
    #    The byte-identical half is already caught by the `duplicate_text`
