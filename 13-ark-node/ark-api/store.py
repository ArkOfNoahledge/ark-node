    def text(self, m):
        """The passage itself: one seek and one readline into the jsonl that
        already holds it. The text is not duplicated anywhere - provenance.sqlite3
        stores a pointer to it, which is why it is 146 MB rather than 3.4 GB."""
        a = self.artifacts[m["src"]]
        p = os.path.join(CHUNKS, a["jsonl"])
        with open(p, "rb") as fh:
            fh.seek(m["off"])
            raw = fh.read(m["len"])
        row = json.loads(raw)
        if row.get("id") != m["cid"]:
            raise RuntimeError(
                "provenance points at %r but the jsonl line is %r - the index was "
                "rebuilt without rebuilding provenance.sqlite3"
                % (m["cid"], row.get("id")))
        return row.get("text", "")

    def citation(self, m):
        """chunk -> artifact -> a URL an operator can open.

        Two shapes, because the archive has two. Twenty-five artifacts are ZIMs
        served by kiwix-serve; four are folders of PDFs that nothing serves, so
        ark-api serves them itself under /files/ and appends the page anchor every
        PDF reader understands."""
        a = self.artifacts[m["src"]]
        out = {
            "artifact": a["file"],
            "shelf": a["shelf"],
            "lang": a["lang"],
            "sha256": a["sha256"],
            "title": m["title"] or m["path"],
            "path": m["path"],
            "chunk": "%d/%d" % (m["i"] + 1, m["n"]),
        }
        if a["kiwix_book"]:
            # THE OBSERVED KEY WINS. a["kiwix_book"] is the filename stem, which
            # is what kiwix-serve 3.8.2 answers to and is NOT what 3.8.1 answers
            # to - 3.8.1 keeps the directory, serving
            # /content/07-corpora-supplemental/mdwiki_en_all_maxi_2025-11. Both
            # were observed against the same library.xml on 2026-09-04. The key is
            # the stored path minus the extension; how much of the path survives
            # is a property of the binary, so it is read from the running server
            # and never constructed here.
            key = self.books.get(m["src"]) or a["kiwix_book"]
            # safe="/" - a key can contain a separator and it must stay one. With
            # safe="" the 3.8.1 form becomes 07-corpora-supplemental%2Fmdwiki...
            # and 404s.
            book = urllib.parse.quote(key, safe="/")
            path = _quasi(m["path"])
            out["kind"] = "zim"
            out["kiwix_book"] = key
            # true only when a running kiwix-serve was asked and answered. Not a
            # claim about the URL being correct - a claim about it having been
            # checked, which is a different and smaller thing.
            out["book_verified"] = m["src"] in self.books
            out["url"] = "%s/viewer#%s/%s" % (KIWIX, book, path)
            out["raw_url"] = "%s/content/%s/%s" % (KIWIX, book, path)
        else:
            out["kind"] = "pdf"
            out["page"] = m["page"]
            rel = "%s/%s" % (a["shelf"], m["path"])
            out["url"] = "/files/%s#page=%s" % (_quasi(rel), m["page"] or 1)
            out["raw_url"] = "/files/%s" % _quasi(rel)
        return out

    def file_path(self, rel):
        """Resolve a /files/ request, refusing anything that escapes the archive.
        The node has one user and no auth by design (§7, 'multi-user accounts and
        permissions' is on the do-not-build list). That is not a reason to serve
        C:\\Windows to whoever is on the WiFi."""
        base = os.path.realpath(ROOT)
        full = os.path.realpath(os.path.join(base, rel.replace("/", os.sep)))
        if not full.startswith(base + os.sep):      # the base itself is a folder
            return None
        return full if os.path.isfile(full) else None

