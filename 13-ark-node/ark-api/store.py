    _NAV_TITLE = re.compile(r"^(category|categoría|tag|tags|index|contents|"
                            r"table of contents|all pages)\b", re.I)

    def is_navigation(self, m, txt):
        """Tag listings and tables of contents match many words and answer nothing.
        Suppressed at query time, never deleted - the same call DECISIONS.md
        records on 2026-09-03, for the same reason: it is reversible."""
        t = (m.get("title") or "")
        if self._NAV_TITLE.match(t):
            return True
        if m.get("path", "").startswith(("Category:", "Tag/", "Special:")):
            return True
        words = txt.split()
        if len(words) > 40:
            uniq = len(set(w.lower() for w in words))
            if uniq / float(len(words)) < 0.35:
                return True
        return False

