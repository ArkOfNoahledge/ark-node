    @staticmethod
    def fuse(dense_ids, sparse_ids):
        """Reciprocal Rank Fusion, k=60. Rank only, never score: cosine similarity
        is 0..1 and BM25 is unbounded and negative, so the two are not comparable
        as numbers. Same constant and same reasoning as bin/index-query.py."""
        score = {}
        for ids in (dense_ids, sparse_ids):
            for rank, cid in enumerate(ids):
                score[cid] = score.get(cid, 0.0) + 1.0 / (RRF_K + rank + 1)
        return sorted(score, key=lambda c: -score[c])

    @staticmethod
    def agreement(n_both):
        """Reported, not hidden. Thresholds and wording from bin/index-query.py,
        which derived them from the five acceptance questions on 2026-09-03. It is
        a pattern from five questions, not a law, and it is labelled as one."""
        if n_both == 0:
            return ("low", "the two retrievers found nothing in common - treat this "
                           "ordering as arbitrary and read the passages, not the ranks")
        if n_both <= 2:
            return ("weak", "one retriever is carrying this result")
        return ("good", "")

