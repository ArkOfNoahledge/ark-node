#
# That is numpy reaching into itself while still initializing: one thread is
# partway through `import numpy`, a second asks for something inside it, finds
# `sys.modules["numpy"]` already present, believes it is finished, and touches a
# module that is still being built. Nothing was wrong with the venv - the same
