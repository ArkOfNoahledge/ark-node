    #
    # THREE RULES, ONE MECHANISM, AND 37.1% OF THE INDEX.
    # Measured 2026-09-11 over all 942,032 documents, not sampled:
    #
    #     iFixit user profile pages   297,242 docs   298,218 chunks   12.88%
    #     wikem translations          89,615 docs    269,471 chunks   11.64%
    #     mdwiki articles wikipedia
