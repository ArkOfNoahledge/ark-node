_NUMPY_READY = False
# THE VERSION THAT ACTUALLY LOADED, recorded 2026-09-17 so the startup line can
# name it. `numpy 2.5.2` is an observation of this process; `numpy is installed`
# would be an inference from the filesystem, and the whole 2026-09-16 entry is
